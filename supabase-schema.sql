create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  genre text not null default 'Drama',
  year integer,
  duration text,
  director text,
  description text,
  accent text,
  symbol text,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  movie_id bigint references public.movies(id) on delete cascade,
  movie_title text not null,
  name text not null,
  age integer not null,
  gender text not null,
  location text not null,
  rating integer not null check (rating between 1 and 5),
  created_at timestamptz not null default now()
);

alter table public.movies enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Public can view movies" on public.movies;
create policy "Public can view movies" on public.movies for select using (true);

drop policy if exists "Public can add movies" on public.movies;
create policy "Public can add movies" on public.movies for insert with check (true);

drop policy if exists "Public can view reviews" on public.reviews;
create policy "Public can view reviews" on public.reviews for select using (true);

drop policy if exists "Public can add reviews" on public.reviews;
create policy "Public can add reviews" on public.reviews for insert with check (true);

grant usage on schema public to anon, authenticated;
grant select, insert on public.movies to anon, authenticated;
grant select, insert on public.reviews to anon, authenticated;
grant usage, select on sequence public.movies_id_seq to anon, authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;

